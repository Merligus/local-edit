DEFAULT_RECIPE_ID = "flux2-klein-4b-q4"

_BY_ID = {r.id: r for r in RECIPES}


def get(recipe_id: str) -> Recipe:
    """A recipe by id, falling back to the default.

    Falls back rather than raising so a settings file naming a recipe this
    version dropped opens the app instead of crashing it on the first read.
    """
    return _BY_ID.get(recipe_id) or _BY_ID[DEFAULT_RECIPE_ID]


def exists(recipe_id: str) -> bool:
    return recipe_id in _BY_ID


def ids() -> tuple[str, ...]:
    return tuple(r.id for r in RECIPES)


def all_files() -> tuple[File, ...]:
    """Every distinct file in the catalog, deduplicated by local filename."""
    seen: dict[str, File] = {}
    for recipe in RECIPES:
        for f in recipe.files:
            seen.setdefault(f.filename(), f)
    return tuple(seen.values())
