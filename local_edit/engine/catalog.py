"""What can be run, what it costs, and how to invoke it. Pure data.

No I/O, no Qt, no network — so it imports without a display and the tests can
check every entry offline.

**A model here is a *recipe*, not a file.** local-upscaler's models were a
`.param`/`.bin` pair of a few megabytes; one entry here is a diffusion
transformer, a text encoder that is itself a 4-8 B language model, a VAE, and
sometimes a vision projector or an adapter — four files and 5-35 GB. Nothing is
bundled: a recipe downloads on demand the first time it is chosen, exactly as
the upscaler's models do, so a checkout stays small and the user pays only for
the tiers they use.

**Every `size` is an exact byte count**, and `fetch` refuses a file that arrives
any other length. This is not belt-and-braces: a captive portal, a rate limit or
a moved URL all return HTTP 200 with an HTML body, and writing that to
`flux-2-klein-4b-Q4_0.gguf` produces a file that fails minutes later inside ggml
with an unreadable error. The counts are machine-generated by `--refresh-sizes`
rather than typed, because a wrong one makes a recipe permanently
un-downloadable and no offline test can catch it.

**The ladder deliberately extends past what the development machine can run.**
It is a GTX 1050 Ti with 3.2 GiB of usable VRAM; `flux2-dev-q4` wants roughly
ten times that. Those rows are not dead weight — `hardware.verdict` grades every
recipe against the machine it is actually on and the UI says which is which, so
the same catalog describes this box today and a larger one later without an
edit here.

`sec_per_mpx_step` and `working_gb` are **priors**, and the honest ones are the
measured figures `settings.Calibration` accumulates after the first run of each
recipe. See `runner.throughput`.
"""

from __future__ import annotations

from dataclasses import dataclass

#: How a recipe is executed. The server keeps multi-gigabyte weights resident
#: between edits, which is the difference between iterating on a prompt and
#: waiting out a fresh model load every time. It is the default. The CLI path
#: exists for recipes whose inputs the server's JSON API cannot express —
#: PhotoMaker takes `--pm-id-images-dir`, a *directory path* that is fixed when
#: the server starts, so a face set cannot be chosen per request.
ENGINE_SERVER = "server"
ENGINE_CLI = "cli"

#: `File.role` -> the sd.cpp flag that points at it. Verified against
#: `sd-cli --help` at commit 7f410a3 rather than read out of the docs, which lag
#: the binary (`--clip-on-cpu` is documented but deprecated in favour of
#: `--backend te=cpu`, and `--llm_vision` takes an underscore where almost every
#: other flag takes a dash).
