HF = "https://huggingface.co"


@dataclass(frozen=True)
class File:
    """One weight file a recipe needs."""

    role: str
    repo: str
    #: Path within the HuggingFace repo.
    path: str
    #: Exact size in bytes. Verified after download; see the module docstring.
    size: int
    #: Local filename. Defaults to the repo path's basename, which is unique
    #: across this catalog; set it only when two repos ship the same basename.
    name: str = ""

    def filename(self) -> str:
        return self.name or self.path.rsplit("/", 1)[-1]

    def subdir(self) -> str:
        return ROLE_DIRS[self.role]

    def url(self) -> str:
        return f"{HF}/{self.repo}/resolve/main/{self.path}"

    def flag(self) -> str:
        return ROLE_FLAGS[self.role]


@dataclass(frozen=True)
class Recipe:
    """One selectable model, and everything needed to run it."""

    id: str
    label: str
    #: Groups recipes that share prompt conventions and reference handling.
    family: str
    blurb: str
    author: str
    licence: str
    url: str
    files: tuple[File, ...]

    # -- how to sample ---------------------------------------------------
    steps: int
    cfg_scale: float
    sampling_method: str = "euler"
    scheduler: str = ""                 # "" means the model's own default
    #: Distilled guidance, for models with a guidance input (Kontext).
    guidance: float | None = None
    flow_shift: float | None = None
    #: Denoise strength when an init image is supplied to a non-edit model.
    strength: float = 0.75
    #: Flags that are always right for this recipe.
    extra_args: tuple[str, ...] = ()
    engine: str = ENGINE_SERVER

    # -- references ------------------------------------------------------
    #: How many reference images the model meaningfully uses. 0 means it takes
    #: none; 1 means one; more means true multi-reference composition.
    max_refs: int = 1
    #: True when references go through `--ref-image`; False when they go
    #: through the single `--ip-adapter-image`, or through PhotoMaker's
    #: id-images directory.
    ref_images: bool = True
    #: How the image being edited reaches the model, and the two families here
    #: differ fundamentally.
    #:
    #: An *edit* model — Kontext, FLUX.2, Qwen-Image-Edit — was trained to see
    #: the image as reference **1** and to read the prompt as an instruction
    #: about it. There is no denoising strength; the model decides what to keep.
    #:
    #: A *generative* model — SD1.5, SDXL — has no such notion. It takes the
    #: image as `--init-img` and partially re-noises it, and `strength` decides
    #: how much of the original survives.
    #:
    #: Getting this backwards is quiet rather than loud: passing an edit model
    #: an init image produces a plausible picture that ignores the instruction,
    #: which looks like a bad model rather than a wiring mistake.
    source_as_ref: bool = True

    # -- shape -----------------------------------------------------------
    default_size: int = 1024
    #: Multiple that width and height are rounded to. Latent patching means an
    #: off-grid size is silently rounded by the engine, which then returns an
    #: image that is not the size the UI promised.
    size_multiple: int = 64

    # -- hardware cost (priors; measurement replaces the timing one) ------
    #: VRAM needed *beyond* the weights at one megapixel — activations,
    #: attention and the sampler's buffers — on a card with usable fp16.
    #: Scaled by `hardware.WORK_EXPONENT`, not linearly, and doubled for a
    #: card without fp16 (every Pascal GPU under Vulkan).
    #:
    #: `flux2-klein-4b-q4` is anchored on sd.cpp's own reported peak compute
    #: buffer; the rest are scaled from it by hidden size.
    working_gb: float = 1.0
    #: Seconds for one sampling step at one megapixel, with no references and
    #: weights resident in VRAM. Scaled by `runner.PIXEL_EXPONENT` rather than
    #: linearly, because attention is quadratic in tokens.
    #:
    #: `flux2-klein-4b-q4` is anchored on a real measurement — 22.3 s/step at
    #: 512x512 on a GTX 1050 Ti under Vulkan. The rest are scaled from it by
    #: parameter count and are honest guesses until `--bench` replaces them.
    sec_per_mpx_step: float = 10.0
    #: Fixed cost of loading the weights and warming the backend.
    load_s: float = 30.0

    # -- derived ---------------------------------------------------------
    def weights_bytes(self) -> int:
        """Total download, and the working set the weights themselves occupy."""
        return sum(f.size for f in self.files)

    def weights_gb(self) -> float:
        return self.weights_bytes() / 1e9

    def file(self, role: str) -> File | None:
        return next((f for f in self.files if f.role == role), None)

    def has(self, role: str) -> bool:
        return self.file(role) is not None

    def uses_photomaker(self) -> bool:
        return self.has("photo_maker")

    def uses_ip_adapter(self) -> bool:
        return self.has("ip_adapter")


